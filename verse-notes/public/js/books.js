export const bookName = (i) => BOOKS[i - 1].name;
export const isSingleChapter = (i) => BOOKS[i - 1].chapters === 1;

// "John 3:16–18", or "Jude 5" for single-chapter books.
export function refString(n) {
  const b = BOOKS[n.book - 1];
  const base = b.chapters === 1 ? `${b.name} ${n.verseStart}` : `${b.name} ${n.chapter}:${n.verseStart}`;
  return n.verseEnd ? `${base}–${n.verseEnd}` : base;
}
